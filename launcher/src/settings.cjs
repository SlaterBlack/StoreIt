const crypto = require('node:crypto');
const path = require('node:path');
const { parse } = require('dotenv');
const { readFileSync } = require('node:fs');

const DEFAULTS = {
  apiHost: '127.0.0.1',
  apiPort: 4002,
  databaseHost: '127.0.0.1',
  databasePort: 5432,
  databaseName: 'storeit',
  databaseUser: 'storeit',
};

function parsePort(value, label) {
  const port = Number(value);
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new Error(`${label} must be a whole number from 1 to 65535.`);
  }
  return port;
}

function validateSettings(input) {
  const apiPort = parsePort(input.apiPort, 'StoreIt API port');
  const databasePort = parsePort(input.databasePort, 'PostgreSQL port');
  if (apiPort === databasePort) {
    throw new Error('The API port and PostgreSQL port must be different.');
  }
  return { apiPort, databasePort };
}

function publicSettings(config) {
  return {
    apiPort: config.apiPort,
    databasePort: config.databasePort,
  };
}

function readSettingsFile(envPath) {
  let values = {};
  try {
    values = parse(readFileSync(envPath));
  } catch (error) {
    if (error.code !== 'ENOENT') {
      throw new Error(`Could not read StoreIt launcher settings: ${error.message}`);
    }
  }

  const settings = validateSettings({
    apiPort: values.PORT ?? DEFAULTS.apiPort,
    databasePort: values.DB_PORT ?? DEFAULTS.databasePort,
  });

  return {
    ...DEFAULTS,
    ...settings,
    databasePassword: values.DB_PASSWORD || crypto.randomBytes(32).toString('base64url'),
    jwtSecret: values.JWT_SECRET || crypto.randomBytes(48).toString('base64url'),
  };
}

function quoteEnvValue(value) {
  return `"${String(value).replaceAll('\\', '\\\\').replaceAll('"', '\\"').replaceAll('\n', '')}"`;
}

function serializeSettings(config) {
  const allowedOrigins = [
    'http://localhost:2400',
    'http://localhost:2401',
    'http://localhost:2402',
    'http://127.0.0.1:2400',
    'http://127.0.0.1:2401',
    'http://127.0.0.1:2402',
  ];
  return [
    '# Generated by the StoreIt desktop launcher.',
    'NODE_ENV=production',
    `API_HOST=${quoteEnvValue(DEFAULTS.apiHost)}`,
    `PORT=${config.apiPort}`,
    `CLIENT_ORIGINS=${quoteEnvValue(allowedOrigins.join(','))}`,
    `DB_HOST=${quoteEnvValue(DEFAULTS.databaseHost)}`,
    `DB_PORT=${config.databasePort}`,
    `DB_NAME=${quoteEnvValue(DEFAULTS.databaseName)}`,
    `DB_USER=${quoteEnvValue(DEFAULTS.databaseUser)}`,
    `DB_PASSWORD=${quoteEnvValue(config.databasePassword)}`,
    'DB_LOGGING=false',
    `JWT_SECRET=${quoteEnvValue(config.jwtSecret)}`,
    'JWT_EXPIRES_IN=1d',
    'BCRYPT_SALT_ROUNDS=10',
    '',
  ].join('\n');
}

function settingsFileFor(userDataDirectory) {
  return path.join(userDataDirectory, '.env');
}

function databaseDirectoryFor(userDataDirectory) {
  return path.join(userDataDirectory, 'postgres-data');
}

function apiHealthUrl(config) {
  return `http://127.0.0.1:${config.apiPort}/api/health`;
}

module.exports = {
  DEFAULTS,
  apiHealthUrl,
  databaseDirectoryFor,
  parsePort,
  publicSettings,
  readSettingsFile,
  serializeSettings,
  settingsFileFor,
  validateSettings,
};
